"""Emit a C validator for the generated multipole kernels.

Checks the EMITTED CODE, not just the DAG: expected values come from the
analytic reference in validate_moment.py, so this closes the loop from
recurrence specification through code generation to executed machine code.
"""
from __future__ import annotations

import math
import os
import sys

sys.path.insert(0, ".")

import recursum_moment_emit as M
from validate_moment import reference_moment

A = (0.11, -0.37, 0.52)
B = (-0.63, 0.24, -0.18)
C = (0.31, 0.17, -0.44)
ALPHA, BETA = 1.7, 0.83


def scalars():
    zeta = ALPHA + BETA
    P = [(ALPHA * A[i] + BETA * B[i]) / zeta for i in range(3)]
    mu = ALPHA * BETA / zeta
    s00 = 1.0
    for i in range(3):
        s00 *= math.exp(-mu * (A[i] - B[i]) ** 2) * math.sqrt(math.pi / zeta)
    return {
        "PA": [P[i] - A[i] for i in range(3)],
        "PC": [P[i] - C[i] for i in range(3)],
        "AB": [A[i] - B[i] for i in range(3)],
        "inv_2zeta": 1.0 / (2.0 * zeta),
        "S00": s00,
    }


def main(outdir):
    sc = scalars()
    L = ['/* AUTO-GENERATED by validate_moment_c.py -- do not edit. */',
         '#include "moment_kernels.h"',
         '#include <math.h>', '#include <stdio.h>', '',
         'static const scdt_onee_scalars S = {',
         "    %.17e, %.17e, %.17e," % tuple(sc["PA"]),
         "    %.17e, %.17e, %.17e," % tuple(sc["PC"]),
         "    %.17e, %.17e, %.17e," % tuple(sc["AB"]),
         "    %.17e" % sc["inv_2zeta"],
         '};',
         "static const double S00 = %.17e;" % sc["S00"], '']

    checks = []
    for la, lb in M.GFN2_PAIRS:
        es = M.moment_set(2)
        outs, _ = M._outputs_for(la, lb, es)
        exp = [reference_moment(o.a, o.b, o.e, ALPHA, BETA, A, B, C) for o in outs]
        nm = M.pair_name(la, lb)
        L.append("static const double EXP_%s[%d] = {" % (nm, len(exp)))
        for i in range(0, len(exp), 4):
            L.append("    " + ", ".join("%.17e" % v for v in exp[i:i + 4]) + ",")
        L.append("};")
        checks.append((nm, len(exp)))
    L.append("")

    L += ['int main(void) {',
          '    double worst = 0.0; int fails = 0;',
          '    double out[4096];',
          '    size_t i;']
    for nm, n in checks:
        L += [f'    scdt_moment_{nm}(&S, S00, out);',
              f'    for (i = 0; i < {n}; i++) {{',
              f'        double e = fabs(out[i] - EXP_{nm}[i]) / S00;',
              '        if (e > worst) worst = e;',
              '    }',
              f'    printf("  %-3s %4d outputs\\n", "{nm}", {n});']
    L += ['    printf("worst |emitted - analytic| / S00 = %.3e\\n", worst);',
          '    if (worst > 1e-14) { printf("FAILED\\n"); fails = 1; }',
          '    else printf("PASSED\\n");',
          '    return fails;',
          '}']
    with open(os.path.join(outdir, "moment_validate.c"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", os.path.join(outdir, "moment_validate.c"))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
